"""Table of contents rules: TOC-01 (exists), TOC-02 (matches headings), TOC-03 (up to date).

Word builds the contents from a TOC field, e.g. TOC \\o "2-3" \\t "Heading 1,1":
  \\o "a-b"   include headings of outline levels a…b,
  \\t "S,n,…" also include paragraphs in style S as level n.
The entries we see are what Word last generated (the field "result").
"""

from __future__ import annotations

import itertools
import re

from ..document_view import FieldView, ParagraphView
from ..model import Location
from .registry import RuleContext, SkipRule, paragraph_location, rule


def _is_main_toc(f: FieldView) -> bool:
    """The table of contents, not a list of figures (TOC \\c "Figure")."""
    return not re.search(r"\\[ca]\b", f.instruction)


def main_toc(ctx: RuleContext) -> FieldView | None:
    tocs = [f for f in ctx.view.fields_named("TOC") if _is_main_toc(f)]
    return tocs[0] if tocs else None


def _switches(instruction: str) -> tuple[tuple[int, int] | None, dict[str, int]]:
    outline = None
    match = re.search(r'\\o\s+"(\d)\s*-\s*(\d)"', instruction)
    if match:
        outline = (int(match.group(1)), int(match.group(2)))
    styles: dict[str, int] = {}
    match = re.search(r'\\t\s+"([^"]*)"', instruction)
    if match:
        parts = [x.strip() for x in re.split(r"[,;]", match.group(1))]
        for name, level in zip(parts[::2], parts[1::2], strict=False):
            if level.isdigit():
                styles[name.casefold()] = int(level)
    if outline is None and not styles:
        outline = (1, 9)
    return outline, styles


def _included_headings(ctx: RuleContext, toc: FieldView) -> list[tuple[ParagraphView, int]]:
    outline, styles = _switches(toc.instruction)
    result = []
    for h in ctx.view.headings:
        style = (h.style_name or "").casefold()
        if style in styles:
            result.append((h, styles[style]))
        elif outline and h.heading_level and outline[0] <= h.heading_level <= outline[1]:
            result.append((h, h.heading_level))
    return result


def _entry_parts(p: ParagraphView) -> tuple[str, str | None]:
    """'1.1.\\tMethods\\t7' -> ('1.1. methods', '7')."""
    pieces = [x.strip() for x in p.text.split("\t") if x.strip()]
    page = None
    if len(pieces) > 1 and re.fullmatch(r"[\divxlcdm]+", pieces[-1], re.IGNORECASE):
        page = pieces.pop()
    elif pieces:
        match = re.match(r"^(.*?)(\d+)$", pieces[-1])
        if match and len(pieces) == 1 and match.group(1).strip():
            pieces[-1], page = match.group(1).strip(), match.group(2)
    return " ".join(" ".join(pieces).split()).casefold(), page


def toc_entries(
    ctx: RuleContext, toc: FieldView
) -> list[tuple[ParagraphView, str, str | None, int | None]]:
    entries = []
    for i in toc.paragraph_indices:
        p = ctx.view.paragraphs[i]
        if p.is_empty:
            continue
        text, page = _entry_parts(p)
        match = re.match(r"^toc (\d)$", (p.style_name or "").casefold())
        entries.append((p, text, page, int(match.group(1)) if match else None))
    return entries


def _heading_key(p: ParagraphView) -> str:
    return " ".join(p.text.split()).casefold()


@rule(
    "TOC-01",
    title="Table of contents exists",
    how_to_fix="References → Table of Contents → Automatic Table (don't type it by hand).",
)
def check_toc_exists(ctx: RuleContext) -> None:
    if main_toc(ctx) is not None:
        return
    typed = any(re.match(r"^toc \d$", (p.style_name or "").casefold()) for p in ctx.view.paragraphs)
    ctx.report(
        message=(
            "The table of contents is typed by hand, not generated by Word."
            if typed
            else "There is no automatic table of contents."
        ),
        location=Location(part="body"),
        expected="an automatic table of contents (TOC field)",
        found="typed by hand" if typed else "none",
    )


@rule(
    "TOC-02",
    title="Contents match the headings",
    how_to_fix="Right-click the table of contents → Update Field → Update entire table.",
)
def check_toc_matches(ctx: RuleContext) -> None:
    toc = main_toc(ctx)
    if toc is None:
        raise SkipRule("No automatic table of contents (see TOC-01).")
    entries = toc_entries(ctx, toc)
    by_text: dict[str, list[int | None]] = {}
    for _, text, _, level in entries:
        by_text.setdefault(text, []).append(level)
    used: set[str] = set()
    for heading, level in _included_headings(ctx, toc):
        key = _heading_key(heading)
        levels = by_text.get(key)
        if not levels:
            ctx.report(
                message="This heading is missing from the table of contents.",
                location=paragraph_location(heading),
                expected="listed in the contents",
                found="not listed",
            )
            continue
        used.add(key)
        if None not in levels and level not in levels:
            ctx.report(
                message=(
                    f"The contents list this heading at level {levels[0]}, but it is level {level}."
                ),
                location=paragraph_location(heading),
                expected=f"level {level}",
                found=f"level {levels[0]}",
            )
    # An entry is wrong only if NO heading has its text (a heading whose style the
    # TOC field leaves out may still be listed by hand; that is not an error here).
    headings = {_heading_key(h) for h in ctx.view.headings}
    for p, text, _, _ in entries:
        if text not in headings:
            ctx.report(
                message="This contents entry has no matching heading in the text.",
                location=paragraph_location(p),
                expected="a heading with the same text",
                found=p.snippet,
            )


@rule(
    "TOC-03",
    title="Contents up to date",
    how_to_fix=(
        "Right-click the table of contents → Update Field → Update entire table. "
        "Auto-fix tells Word to update all fields when the file is opened."
    ),
)
def check_toc_fresh(ctx: RuleContext) -> None:
    toc = main_toc(ctx)
    if toc is None:
        raise SkipRule("No automatic table of contents (see TOC-01).")
    entries = toc_entries(ctx, toc)
    joined = " ".join(p.text for p, *_ in entries).casefold()
    problem = None
    if not entries or "no table of contents entries" in joined or "error!" in joined:
        problem = "is empty or shows an error"
    else:
        pages = [int(page) for _, _, page, _ in entries if page and page.isdigit()]
        if any(b < a for a, b in itertools.pairwise(pages)):
            problem = "has page numbers that go backwards"
    if problem:
        first = ctx.view.paragraphs[toc.paragraph_indices[0]]
        ctx.report(
            message=f"The table of contents {problem}, so it looks out of date.",
            location=paragraph_location(first),
            expected="an updated table of contents",
            found=problem,
        )
